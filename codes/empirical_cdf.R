load("data/empirical_cdf.RData")
draw=function(){
  x=sort(x)
  n=length(x)
  sf=stepfun(x,c(0:n)/n)
  par(mar=c(4,4,2,1))
  plot(sf,xlim=c(55,100),ylim=c(0,1),xlab="Score",ylab="F_n(x)",main="Empirical Distribution Function F_n(x)",verticals=TRUE,do.points=FALSE,lwd=1.5)
  points(x,c(1:n)/n,pch=19,cex=0.9)
  points(x,c(0:(n-1))/n,pch=21,cex=0.9)
}
pdf("../figures/empirical_cdf.pdf",width=8,height=4)
draw()
dev.off()
